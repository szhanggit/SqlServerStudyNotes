CREATE TABLE [merchant_info].[tb_contract] (
    [id]                      INT             IDENTITY (1, 1) NOT NULL,
    [contract_name]           NVARCHAR (128)  NOT NULL,
    [start_date]              DATETIME        NOT NULL,
    [end_date]                DATETIME        NOT NULL,
    [payment_term_id]         INT             NOT NULL,
    [price_option_id]         INT             NOT NULL,
    [cost_scheme_id]          INT             NOT NULL,
    [cost_percentage]         DECIMAL (18, 4) NULL,
    [cost_rounding_rule_id]   INT             NULL,
    [cost_rounding_places_id] INT             NULL,
    [sku_quantity]            INT             NOT NULL,
    [status_id]               INT             NOT NULL,
    [merchant_id]             INT             NOT NULL,
    [created_by]              NVARCHAR (50)   NULL,
    [created_datetime]        DATETIME        NULL,
    [contract_number]         AS              (CONVERT([varchar](13),format([id],'0000000000000'))),
    [updated_by]              NVARCHAR (50)   NULL,
    [updated_datetime]        DATETIME        NULL,
    [timestamp]               ROWVERSION      NOT NULL,
    CONSTRAINT [PK_tb_contract] PRIMARY KEY CLUSTERED ([id] ASC),
    CONSTRAINT [FK_contract_cost_rounding_places] FOREIGN KEY ([cost_rounding_places_id]) REFERENCES [merchant_info].[tb_contract_cost_rounding_places] ([id]),
    CONSTRAINT [FK_contract_cost_rounding_rule] FOREIGN KEY ([cost_rounding_rule_id]) REFERENCES [merchant_info].[tb_contract_cost_rounding_rule] ([id]),
    CONSTRAINT [FK_contract_cost_scheme] FOREIGN KEY ([cost_scheme_id]) REFERENCES [merchant_info].[tb_contract_cost_scheme] ([id]),
    CONSTRAINT [FK_contract_merchant] FOREIGN KEY ([merchant_id]) REFERENCES [merchant_info].[tb_m_merchant] ([id]),
    CONSTRAINT [FK_contract_payment_term] FOREIGN KEY ([payment_term_id]) REFERENCES [merchant_info].[tb_contract_payment_term] ([id]),
    CONSTRAINT [FK_contract_price_option] FOREIGN KEY ([price_option_id]) REFERENCES [merchant_info].[tb_contract_price_option] ([id]),
    CONSTRAINT [FK_contract_status] FOREIGN KEY ([status_id]) REFERENCES [merchant_info].[tb_contract_status] ([id])
);

